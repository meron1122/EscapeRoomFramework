"""Writes the broker ACL for browsers from a room definition.

A browser (the simulator) may read the room's topics and may write only where the room's own sensors write:
the input topics, the start/speed control topic and the player-tracking topic. It cannot write to outputs
(voice, screens, doors, lamps, twists), to another room, or to anything the safety layer listens on.
Usage: python3 make-acl.py <room-id> <room.json> > browser.acl
"""
import json, sys

room_id, path = sys.argv[1], sys.argv[2]
room = json.load(open(path, encoding="utf-8"))

def topic(io):  # only plain-topic devices are simulated in a browser
    return io.get("topic")

inputs = sorted({t for t in map(topic, room["inputs"].values()) if t})
outputs = {t for t in map(topic, room["outputs"].values()) if t}
clash = [t for t in inputs if t in outputs]
if clash:
    sys.exit(f"input and output share a topic: {clash}")
for t in inputs:
    if "#" in t or "+" in t:
        sys.exit(f"wildcard in input topic: {t}")

print(f"# Generated by make-acl.py from {path}. Do not edit by hand.")
print(f"topic read escaperoom/{room_id}/#")
for prefix in sorted({t.split('/')[0] + '/' + t.split('/')[1] for t in outputs | set(inputs) if not t.startswith('escaperoom/')}):
    print(f"topic read {prefix}/#")
print(f"topic write escaperoom/{room_id}/control")
print(f"topic write escaperoom/{room_id}/players")
for t in inputs:
    print(f"topic write {t}")
